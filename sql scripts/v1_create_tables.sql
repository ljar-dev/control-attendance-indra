    user_agent VARCHAR2(500),
    CONSTRAINT fk_log_attendance FOREIGN KEY (id_attendance_record) 
        REFERENCES attendance_records(id_attendance_record) ON DELETE CASCADE,
    CONSTRAINT fk_log_employee FOREIGN KEY (employee_id) 
